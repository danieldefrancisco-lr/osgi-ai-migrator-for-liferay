package io.github.danieldefrancisco_lr.migrator.core.analyzer;

import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Finds the custom business logic of a legacy module that must be ported: the methods of Model Listeners,
 * Service Wrappers and Service Builder *LocalServiceImpl classes, with the Object Action trigger each one maps to.
 */
public class CustomLogicExtractor {

    public enum Kind { MODEL_LISTENER, SERVICE_WRAPPER, LOCAL_SERVICE_IMPL }

    /** One method with logic to port. */
    public static class LogicUnit {
        public final String className;
        public final Kind kind;
        public final String method;
        public final String body;
        /** Object Action trigger (onAfterAdd, onAfterUpdate, onAfterDelete), "query" for read methods, or "standalone". */
        public final String target;
        /** The body only logs: Liferay's entry history replaces it, no action is needed. */
        public final boolean loggingOnly;
        /** The body calls an external system over HTTP. */
        public final boolean callsExternalSystem;

        LogicUnit(String className, Kind kind, String method, String body) {
            this.className = className;
            this.kind = kind;
            this.method = method;
            this.body = body;
            this.target = targetOf(kind, method);
            this.loggingOnly = isLoggingOnly(body);
            this.callsExternalSystem = EXTERNAL_CALL.matcher(body).find();
        }

        /** e.g. "LoanModelListener.onAfterUpdate (model listener) -> onAfterUpdate, calls an external system" */
        public String summary() {
            StringBuilder sb = new StringBuilder(className).append(".").append(method)
                .append(" (").append(kind.name().toLowerCase().replace('_', ' ')).append(") -> ").append(target);
            if (loggingOnly) {
                sb.append(", logging only");
            } else if (callsExternalSystem) {
                sb.append(", calls an external system");
            }
            return sb.toString();
        }
    }

    private static final Pattern EXTERNAL_CALL = Pattern.compile(
        "HttpClient|HttpURLConnection|HttpRequest|RestTemplate|WebClient|URLConnection|\\.openConnection\\(|HttpUtil|Http\\.Options");

    /** A method declaration at class level: modifiers, return type, name, parameters, optional throws, then '{'. */
    private static final Pattern METHOD = Pattern.compile(
        "(?:public|protected)\\s+(?:static\\s+|final\\s+|synchronized\\s+)*[\\w<>\\[\\],.? ]+?\\s+(\\w+)\\s*\\([^)]*\\)\\s*(?:throws\\s+[\\w.,\\s]+)?\\{");

    private static final Pattern LOG_STATEMENT = Pattern.compile(
        "(?:System\\.(?:out|err)\\.print(?:ln|f)?|_?log(?:ger)?\\.(?:info|debug|trace|warn|error|isDebugEnabled|isInfoEnabled))\\s*\\(");

    /** The units of one Java source file, or none when it is not a listener, wrapper or local service implementation. */
    public static List<LogicUnit> extract(String fileName, String content) {
        List<LogicUnit> units = new ArrayList<>();
        Kind kind = kindOf(fileName, content);
        if (kind == null) {
            return units;
        }
        String className = fileName.endsWith(".java") ? fileName.substring(0, fileName.length() - 5) : fileName;
        String code = blankCommentsAndStrings(content);
        int classBody = code.indexOf('{', Math.max(0, code.indexOf(" class ")));
        if (classBody < 0) {
            return units;
        }
        Matcher m = METHOD.matcher(code);
        int from = classBody + 1;
        while (from < code.length() && m.find(from)) {
            int open = m.end() - 1;
            if (depthAt(code, classBody, m.start()) != 1) {
                from = m.end();
                continue;
            }
            int close = matchingBrace(code, open);
            if (close < 0) {
                break;
            }
            String body = content.substring(open + 1, close).trim();
            if (!body.isEmpty()) {
                units.add(new LogicUnit(className, kind, m.group(1), body));
            }
            from = close + 1;
        }
        return units;
    }

    static Kind kindOf(String fileName, String content) {
        if (fileName.endsWith("LocalServiceImpl.java")) {
            // Base*LocalServiceImpl is generated by Service Builder
            return fileName.startsWith("Base") ? null : Kind.LOCAL_SERVICE_IMPL;
        }
        if (content.contains("BaseModelListener") || content.contains("implements ModelListener")) {
            return Kind.MODEL_LISTENER;
        }
        if (content.contains("LocalServiceWrapper") || content.contains("ServiceWrapper")) {
            return Kind.SERVICE_WRAPPER;
        }
        return null;
    }

    static String targetOf(Kind kind, String method) {
        String m = method.toLowerCase();
        if (kind == Kind.MODEL_LISTENER) {
            if (m.contains("create")) return "onAfterAdd";
            if (m.contains("update")) return "onAfterUpdate";
            if (m.contains("remove")) return "onAfterDelete";
            return "standalone";
        }
        if (m.startsWith("add") || m.startsWith("create")) return "onAfterAdd";
        if (m.startsWith("update")) return "onAfterUpdate";
        if (m.startsWith("delete") || m.startsWith("remove")) return "onAfterDelete";
        if (m.startsWith("get") || m.startsWith("find") || m.startsWith("count") || m.startsWith("search") || m.startsWith("fetch")) {
            return "query";
        }
        return "standalone";
    }

    /** Whether every statement of the body is a log call (or the body only delegates to super). */
    static boolean isLoggingOnly(String body) {
        String code = blankCommentsAndStrings(body);
        boolean any = false;
        for (String statement : code.split(";")) {
            String s = statement.trim();
            if (s.isEmpty()) {
                continue;
            }
            any = true;
            if (!LOG_STATEMENT.matcher(s).find() && !s.startsWith("if (_log.is") && !s.equals("}")) {
                return false;
            }
        }
        return any;
    }

    /** Replaces comments and string/char literals with spaces, keeping offsets, so braces inside them are ignored. */
    static String blankCommentsAndStrings(String s) {
        char[] out = s.toCharArray();
        int i = 0;
        while (i < out.length) {
            char c = out[i];
            if (c == '/' && i + 1 < out.length && out[i + 1] == '/') {
                while (i < out.length && out[i] != '\n') out[i++] = ' ';
            } else if (c == '/' && i + 1 < out.length && out[i + 1] == '*') {
                while (i < out.length && !(out[i] == '*' && i + 1 < out.length && out[i + 1] == '/')) {
                    if (out[i] != '\n') out[i] = ' ';
                    i++;
                }
                if (i < out.length) { out[i++] = ' '; }
                if (i < out.length) { out[i++] = ' '; }
            } else if (c == '"' || c == '\'') {
                char quote = c;
                i++;
                while (i < out.length && out[i] != quote) {
                    if (out[i] == '\\' && i + 1 < out.length) { out[i++] = ' '; }
                    if (out[i] != '\n') out[i] = ' ';
                    i++;
                }
                i++;
            } else {
                i++;
            }
        }
        return new String(out);
    }

    private static int depthAt(String code, int classBody, int index) {
        int depth = 0;
        for (int i = classBody; i < index; i++) {
            char c = code.charAt(i);
            if (c == '{') depth++;
            else if (c == '}') depth--;
        }
        return depth;
    }

    private static int matchingBrace(String code, int open) {
        int depth = 0;
        for (int i = open; i < code.length(); i++) {
            char c = code.charAt(i);
            if (c == '{') depth++;
            else if (c == '}' && --depth == 0) return i;
        }
        return -1;
    }
}
